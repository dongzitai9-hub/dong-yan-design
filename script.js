function syncHistory(state, hash) {
  const nextUrl = `${location.pathname}${location.search}${hash}`;
  if (location.hash === hash) {
    history.replaceState(state, "", nextUrl);
    return;
  }
  history.pushState(state, "", nextUrl);
}

