function setActiveService(index) {
  if (!serviceTitle || !serviceCopy || !serviceCards.length) return;
  const nextIndex = (index + serviceItems.length) % serviceItems.length;
  const item = serviceItems[nextIndex];
  serviceTitle.textContent = item.title;
  serviceCopy.textContent = item.copy;
  if (serviceNote) serviceNote.textContent = item.note;
  serviceCards.forEach((card) => {
    const cardIndex = Number(card.dataset.serviceIndex);
    const isActive = cardIndex === nextIndex;
    const visualOrder = (cardIndex - nextIndex + serviceItems.length) % serviceItems.length;
    card.classList.toggle("is-active", isActive);
    card.style.order = visualOrder;
  });
}

function bindServiceShowcase() {
  if (!serviceCards.length) return;
  let activeIndex = 0;
  serviceCards.forEach((card) => {
    const item = serviceItems[Number(card.dataset.serviceIndex)];
    if (item) card.dataset.serviceLabel = item.title;
  });
  const activate = (index) => {
    activeIndex = (index + serviceItems.length) % serviceItems.length;
    setActiveService(activeIndex);
  };
  serviceCards.forEach((card) => {
    card.addEventListener("click", () => {
      const clickedIndex = Number(card.dataset.serviceIndex);
      activate(clickedIndex);
    });
  });
  setActiveService(activeIndex);
}

function bindNavDropdowns() {
  navDropdowns.forEach((dropdown) => {
    const open = () => dropdown.classList.add("is-open");
    const close = () => dropdown.classList.remove("is-open");
    dropdown.addEventListener("mouseenter", open);
    dropdown.addEventListener("mouseleave", close);
    dropdown.addEventListener("focusin", open);
    dropdown.addEventListener("focusout", (event) => {
      if (!dropdown.contains(event.relatedTarget)) close();
    });
  });

  document.querySelectorAll(".nav-dropdown-panel a").forEach((link) => {
    link.addEventListener("click", (event) => {
      const href = link.getAttribute("href") || "";
      const spaceMatch = href.match(/\/cases\/space-(\d+)\/?/);
      const schemeMatch = href.match(/\/cases\/scheme-(\d+)\/?/);
      if (spaceMatch) {
        event.preventDefault();
        openCaseView(Number(spaceMatch[1]) - 1);
        return;
      }
      if (schemeMatch) {
        event.preventDefault();
        openSchemeView(Number(schemeMatch[1]) - 1);
        return;
      }
      if (href === "/cases/") {
        event.preventDefault();
        const isPlans = link.closest(".nav-dropdown-panel")?.getAttribute("aria-label")?.includes("方案");
        if (isPlans) openSchemeList();
        else openCaseList();
        return;
      }
      if (href.startsWith("/notes/")) {
        event.preventDefault();
        openNotesList();
        return;
      }
      if (href === "#contact" || href === "/about/" || href === "/services/" || href === "/faq/") {
        event.preventDefault();
        openContactView();
      }
    });
  });
}

function setLightboxImage(index) {
  if (!lightboxImages.length) return;
  lightboxIndex = (index + lightboxImages.length) % lightboxImages.length;
  const item = lightboxImages[lightboxIndex];
  lightboxImg.src = item.image;
  lightboxImg.alt = item.title || "空间图片";
}

function openLightbox(image, alt, gallery = []) {
  lightboxImages = gallery.length ? gallery : [{ image, title: alt }];
  const nextIndex = lightboxImages.findIndex((item) => item.image === image);
  setLightboxImage(nextIndex >= 0 ? nextIndex : 0);
  lightbox.hidden = false;
}

function moveLightbox(direction) {
  if (lightbox.hidden || lightboxImages.length < 2) return;
  setLightboxImage(lightboxIndex + direction);
}

function syncHistory(state, hash) {
  const nextUrl = `${location.pathname}${location.search}${hash}`;
  if (location.hash === hash) {
    history.replaceState(state, "", nextUrl);
    return;
  }
  history.pushState(state, "", nextUrl);
}

